#!/usr/bin/env node
/**
 * Scan public/art/<id>/*.png and write src/data/artManifest.ts, so the game only loads art that
 * exists (enemy art arrives a few sheets at a time). Run after adding or removing art
 * (tools/add-art.mjs does it for you).
 */
import { existsSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const artDir = join(root, 'public', 'art');
const out = {};
for (const id of readdirSync(artDir).sort()) {
  const dir = join(artDir, id);
  if (!statSync(dir).isDirectory() || !existsSync(join(dir, 'anchors.json'))) continue;
  out[id] = readdirSync(dir).filter((f) => f.endsWith('.png')).map((f) => f.slice(0, -4)).sort();
}
// plain image folders (no anchors needed): item/troop icons and town backgrounds
// backgrounds are JPEG (no transparency needed, a quarter of the size); the file extension of
// each picture in these folders is recorded in ART_EXT
const ext = {};
const pngsIn = (sub) => {
  const d = join(artDir, sub);
  if (!existsSync(d)) return [];
  return readdirSync(d)
    .filter((f) => /\.(png|jpg)$/.test(f))
    .map((f) => {
      const [name, e] = [f.replace(/\.(png|jpg)$/, ''), f.split('.').pop()];
      if (e !== 'png') ext[`${sub}/${name}`] = e;
      return name;
    })
    .sort();
};
const icons = pngsIn('icons');
const town = pngsIn('town');
const scenes = pngsIn('scenes');
const battle = pngsIn('battle');
const body = Object.entries(out)
  .map(([id, poses]) => `  ${JSON.stringify(id)}: [${poses.map((p) => `'${p}'`).join(', ')}],`)
  .join('\n');
writeFileSync(
  join(root, 'src', 'data', 'artManifest.ts'),
  `// Generated by tools/art-manifest.mjs — do not edit by hand.\n/** Frame-art images that exist under public/art/<id>/ (anchors.json alongside). */\nexport const ART_FILES: Record<string, string[]> = {\n${body}\n};\n\n/** Icons that exist under public/art/icons/ (others are drawn as placeholder circles). */\nexport const ICON_FILES: string[] = [${icons.map((k) => `'${k}'`).join(', ')}];\n\n/** Town pictures under public/art/town/ (the town is drawn with shapes until they exist). */\nexport const TOWN_FILES: string[] = [${town.map((k) => `'${k}'`).join(', ')}];\n\n/** Title and story pictures under public/art/scenes/ (title.png, <scenarioId>.png). */\nexport const SCENE_FILES: string[] = [${scenes.map((k) => `'${k}'`).join(', ')}];\n\n/** Battle backgrounds under public/art/battle/ (<scenarioId>-sky.png, <scenarioId>-ground.png). */\nexport const BATTLE_FILES: string[] = [${battle.map((k) => `'${k}'`).join(', ')}];\n\n/** Pictures stored in another format than PNG ("folder/name" → extension). */\nexport const ART_EXT: Record<string, string> = ${JSON.stringify(ext)};\n\n/** URL of a picture in one of the plain folders (icons, town, scenes, battle). */\nexport const artUrl = (folder: string, name: string) => \`\${import.meta.env.BASE_URL}art/\${folder}/\${name}.\${ART_EXT[folder + '/' + name] ?? 'png'}\`;\n`,
);
console.log(`art manifest: ${Object.keys(out).length} characters, ${icons.length} icons, ${town.length} town images, ${scenes.length} scene images, ${battle.length} battle layers`);
