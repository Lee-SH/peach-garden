#!/usr/bin/env node
/**
 * Scan public/art/<id>/*.png and write src/data/artManifest.ts, so the game only loads art that
 * exists (enemy art arrives a few sheets at a time). Run after adding or removing art
 * (tools/add-art.mjs does it for you).
 */
import { existsSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const artDir = join(root, 'public', 'art');
const out = {};
for (const id of readdirSync(artDir).sort()) {
  const dir = join(artDir, id);
  if (!statSync(dir).isDirectory() || !existsSync(join(dir, 'anchors.json'))) continue;
  out[id] = readdirSync(dir).filter((f) => f.endsWith('.png')).map((f) => f.slice(0, -4)).sort();
}
// item/troop icons: public/art/icons/<key>.png (no anchors needed)
const iconDir = join(artDir, 'icons');
const icons = existsSync(iconDir) ? readdirSync(iconDir).filter((f) => f.endsWith('.png')).map((f) => f.slice(0, -4)).sort() : [];
const body = Object.entries(out)
  .map(([id, poses]) => `  ${JSON.stringify(id)}: [${poses.map((p) => `'${p}'`).join(', ')}],`)
  .join('\n');
writeFileSync(
  join(root, 'src', 'data', 'artManifest.ts'),
  `// Generated by tools/art-manifest.mjs — do not edit by hand.\n/** Frame-art images that exist under public/art/<id>/ (anchors.json alongside). */\nexport const ART_FILES: Record<string, string[]> = {\n${body}\n};\n\n/** Icons that exist under public/art/icons/ (others are drawn as placeholder circles). */\nexport const ICON_FILES: string[] = [${icons.map((k) => `'${k}'`).join(', ')}];\n`,
);
console.log(`art manifest: ${Object.keys(out).length} characters, ${icons.length} icons`);
